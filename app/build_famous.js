/* Precomputes planetary longitudes for the famous-chart database -> famous_data.js
   Usage: node build_famous.js ../build/people.json */
const fs = require("fs"), vm = require("vm");
const b = __dirname + "/";
const ctx = {console, Intl, Date, Math, Object, Array, Set, JSON, String, Number};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(b + "astronomy.min.js", "utf8") + "\n;this.Astronomy = Astronomy;", ctx);
for (const f of ["engine.js", "famous.js"]) vm.runInContext(fs.readFileSync(b + f, "utf8"), ctx);
ctx.PEOPLE = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const out = vm.runInContext(`
const INFAMOUS = /serial killer|mass murder|dictator|cult|terroris|war criminal|convicted|assassin|criminal|gangster|mobster|drug lord|fraudster|nazi|school shooter|spree|murderer|rapist|con artist|ponzi/i;
const NON = /fictional|character|puppet/i;
const rows = [], seen = new Set();
const r1 = x => Math.round(x * 10) / 10;
const pack = (c) => [r1(c.lonOf.Sun), r1(c.lonOf.Moon), r1(c.lonOf.Mercury), r1(c.lonOf.Venus), r1(c.lonOf.Mars), r1(c.lonOf.Jupiter), r1(c.lonOf.Saturn), r1(c.lonOf.Uranus), r1(c.lonOf.Neptune), r1(c.lonOf.Pluto), r1(c.lonOf.Node)];
const nrm = s => s.toLowerCase().replace(/[^a-z]/g, "");
for (const f of FAMOUS) {
  const c = famousChart(f);
  rows.push([f[0], f[1], f[2], f[3], f[8], pack(c), r1(c.asc), r1(c.mc)]);
  seen.add(nrm(f[0]));
}
const LIMIT = 1000;
for (const p of PEOPLE) {
  if (rows.length >= LIMIT) break;
  const n = nrm(p.name);
  if (seen.has(n) || NON.test(p.desc || "")) continue;
  const [y, m, d] = p.dob.split("-").map(Number);
  if (!y || !m || !d) continue;
  const utc = new Date(Date.UTC(y, m - 1, d, 12) - p.lon / 15 * 3600000);
  const c = {lonOf: planetsAt(utc).lon};
  seen.add(n);
  rows.push([p.name, p.desc || "Notable person", INFAMOUS.test(p.desc || "") ? "Infamous" : "Notable", p.dob, p.where || "", pack(c), null, null]);
}
JSON.stringify(rows);
`, ctx);
const rows = JSON.parse(out);
fs.writeFileSync(b + "famous_data.js", "/* Generated by build_famous.js. Birth dates/places: Wikidata (CC0). Entries without a time use local noon. */\nconst FAMOUS_DB = " + JSON.stringify(rows) + ";\n");
console.log("rows", rows.length, "bytes", fs.statSync(b + "famous_data.js").size);

